#!/usr/bin/env bash
#
# Export the local `general` conda env into the lock files the image build reads.
#
# Run this LOCALLY, on the machine whose env is the reference, whenever that env changes on
# purpose. The cluster never sees this machine: `hpc/general.def.in` installs exactly what the
# lock files say, so the two files it writes are checked in next to it.
#
#   hpc/requirements-cu128.lock   every pip package of the env, pinned, torch cu128
#   hpc/requirements-cu126.lock   the same with torch cu126: the dgx2 image (V100, sm_70,
#                                 which the cu128 torch wheels do not carry)
#   hpc/env.lock.env              python version, Isaac Lab commit, provenance
#
# What is dropped, and why:
#   * editable installs (`-e git+...`): Isaac Lab is cloned at its recorded commit by the
#     image build, and the research repos are BOUND into the job, never installed.
#   * conda-built `name @ file:///...croot/...` lines (jupyter and friends): replaced by
#     `name==version`, which PyPI has.
#   * `pip freeze --all`, so pip, setuptools and wheel are pinned too: the image installs
#     the lock WITHOUT build isolation, and the source-only wheels in it (flatdict) build
#     against the env's own setuptools, as they did locally. A newer setuptools has no
#     pkg_resources and the build fails.
#   * in the cu126 lock only: the `nvidia-*-cu12` pins are REPLACED by the versions the
#     torch cu126 wheel itself requires, read from its published wheel metadata (PEP 658) on
#     download.pytorch.org -- the image installs with `--no-deps`, so every wheel must be
#     named explicitly.
#
# Why `--no-deps` in the image: the env's pins do not satisfy Isaac Sim's own declared
# requirements (isaacsim-kernel wants numpy==1.26.0, the env runs 1.26.4; `pip check` lists
# ten such lines locally). pip's resolver would refuse the set; `--no-deps` installs the env
# exactly as it is, which is the point of a lock.
#
# Every knob is env-overridable.

set -Eeuo pipefail
trap 'echo "[export_env] FAILED at ${BASH_SOURCE[0]}:${LINENO}: ${BASH_COMMAND}" >&2' ERR

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
: "${GENERAL_PYTHON:=${HOME}/miniconda3/envs/general/bin/python}"
: "${LOCK_CU128:=${HERE}/requirements-cu128.lock}"
: "${LOCK_CU126:=${HERE}/requirements-cu126.lock}"
: "${ENV_LOCK:=${HERE}/env.lock.env}"

say() { echo "[export_env] $*"; }

if [[ ! -x "${GENERAL_PYTHON}" ]]; then
    echo "[export_env] GENERAL_PYTHON is not executable: ${GENERAL_PYTHON}" >&2
    exit 2
fi
say "env python : ${GENERAL_PYTHON}"

# The torch cu126 wheel's metadata (PEP 658), fetched with curl: python's urllib hangs on
# download.pytorch.org from some networks, curl does not.
TORCH_VERSION="$("${GENERAL_PYTHON}" -c 'from importlib import metadata; print(metadata.version("torch").split("+")[0])')"
PY_TAG="$("${GENERAL_PYTHON}" -c 'import sys; print(f"cp{sys.version_info.major}{sys.version_info.minor}")')"
META_URL="https://download.pytorch.org/whl/cu126/torch-${TORCH_VERSION}%2Bcu126-${PY_TAG}-${PY_TAG}-manylinux_2_28_x86_64.whl.metadata"
META_FILE="$(mktemp)"
trap 'rm -f "${META_FILE}"' EXIT
say "torch cu126 metadata: ${META_URL}"
curl -fsSL --max-time 60 -o "${META_FILE}" "${META_URL}"

"${GENERAL_PYTHON}" - "${LOCK_CU128}" "${LOCK_CU126}" "${ENV_LOCK}" "${META_FILE}" "${META_URL}" <<'PYEOF'
import hashlib
import platform
import re
import socket
import subprocess
import sys
from datetime import date
from importlib import metadata

lock_cu128, lock_cu126, env_lock, meta_file, meta_url = sys.argv[1:6]

freeze = subprocess.run(
    [sys.executable, "-m", "pip", "freeze", "--all"], check=True, capture_output=True, text=True
).stdout.splitlines()

ISAACLAB_RE = re.compile(r"^-e git\+(?P<url>\S+?)@(?P<sha>[0-9a-f]{40})#egg=isaaclab&")
pinned, dropped, isaaclab = [], [], None
for line in freeze:
    line = line.strip()
    if not line:
        continue
    if line.startswith("-e "):
        match = ISAACLAB_RE.match(line)
        if match:
            isaaclab = (match["url"], match["sha"])
        dropped.append(line)
        continue
    if " @ file://" in line:
        name = line.split(" @ ", 1)[0]
        pinned.append(f"{name}=={metadata.version(name)}")
        continue
    if "==" not in line:
        raise SystemExit(f"[export_env] cannot pin freeze line: {line!r}")
    pinned.append(line)

if isaaclab is None:
    raise SystemExit("[export_env] no editable Isaac Lab install in the env; refusing")
if not any(p.startswith("torch==") and p.endswith("+cu128") for p in pinned):
    raise SystemExit("[export_env] the env's torch is not a +cu128 build; the def assumes it")
if not any(p.startswith("isaacsim==") for p in pinned):
    raise SystemExit("[export_env] no isaacsim wheel in the env; refusing")

pinned.sort(key=str.lower)
header = (
    "# generated by hpc/export_env.sh -- do not edit by hand\n"
    f"# source env: {sys.executable} on {socket.gethostname()}, {date.today()}\n"
    f"# python {platform.python_version()}\n"
)
with open(lock_cu128, "w") as f:
    f.write(header + "# flavor: cu128\n" + "\n".join(pinned) + "\n")

# The cu126 flavor: the same env with torch rebuilt for sm_70. Its nvidia-* wheels differ,
# and `--no-deps` means they must be named, so read them off the cu126 wheel's metadata.
torch_meta = open(meta_file).read()
REQ_RE = re.compile(r"^Requires-Dist: (nvidia-[a-z0-9-]+)==([0-9.]+)", re.M)
cu126_nvidia = {name.lower(): f"{name}=={version}" for name, version in REQ_RE.findall(torch_meta)}
if not cu126_nvidia:
    raise SystemExit(f"[export_env] no nvidia-* pins found in {meta_url}")

cu126, replaced = [], 0
for p in pinned:
    name = p.split("==", 1)[0].lower()
    if name.startswith("nvidia-") and name.endswith("-cu12"):
        if name not in cu126_nvidia:
            raise SystemExit(f"[export_env] {name} is in the env but not required by torch cu126; "
                             "decide by hand whether the cu126 lock needs it")
        cu126.append(cu126_nvidia.pop(name))
        replaced += 1
        continue
    cu126.append(p.replace("+cu128", "+cu126"))
# anything torch cu126 needs that the cu128 env did not have
cu126.extend(sorted(cu126_nvidia.values(), key=str.lower))
cu126.sort(key=str.lower)
with open(lock_cu126, "w") as f:
    f.write(header + f"# flavor: cu126 (torch rebuilt for sm_70; {replaced} nvidia-* pins taken "
            f"from {meta_url})\n" + "\n".join(cu126) + "\n")

digest = hashlib.sha256(open(lock_cu128, "rb").read()).hexdigest()[:16]
url, sha = isaaclab
if url.endswith(".git"):
    pass
with open(env_lock, "w") as f:
    f.write(
        "# generated by hpc/export_env.sh -- do not edit by hand\n"
        f"PYTHON_VERSION={platform.python_version()}\n"
        f"PYTHON_MINOR={'.'.join(platform.python_version_tuple()[:2])}\n"
        f"ISAACLAB_REPO={url}\n"
        f"ISAACLAB_COMMIT={sha}\n"
        f"ISAACSIM_VERSION={metadata.version('isaacsim')}\n"
        f"TORCH_VERSION={metadata.version('torch')}\n"
        f"LOCK_SHA256_16={digest}\n"
        f"EXPORTED_ON={date.today()}\n"
        f"EXPORTED_FROM={socket.gethostname()}\n"
    )

print(f"[export_env] {len(pinned)} pins -> {lock_cu128}")
print(f"[export_env] {len(cu126)} pins -> {lock_cu126}")
print(f"[export_env] dropped {len(dropped)} editable install(s):")
for d in dropped:
    print("              ", d.split("#egg=")[-1] if "#egg=" in d else d)
print(f"[export_env] isaac lab {sha[:10]} from {url}")
PYEOF

say "wrote ${ENV_LOCK}"
cat "${ENV_LOCK}"
